#!/usr/bin/env node
// 把员工导出的板材包合进网站（负责人用）。
//
//   node scripts/import-boards.mjs --pack WISH-boards-20261024.json [WISH-boards-20261024-p2of2.json …]
//        [--meta-only] [--out public/boards] [--library src/shared/boards/library.js] [--dry] [--force] [--remove <id> …]
//
// 板材包 = 办公室电脑「员工 · 案例库 → 板材 → 导入板材文件夹」做好、「导出板材包」存下来的 JSON（每份 ≤ 20 MB，一份一份都能单独合）。
//   默认（老板已同意：压缩过的板材贴图可以放在公开网站上）：贴图写到 <out>/<id>/{256,1024,chip}.webp（WebP 字节原样写，不重新编码），
//         记录合进 src/shared/boards/library.js（img: true）→ 任何设备打开网站都看得到真实板材。
//   --meta-only：只合资料（名字、颜色、尺寸、近似色木纹的参数），不写贴图（img: false）→ 别的设备用近似色；
//         已经导入过板材包的设备（店里的 iPad）照样用自己的贴图。
//   --dry：只看会发生什么，什么都不写。
//   --force：同一个 id、同一个 rev 也用包里的那份（默认：rev 高的赢，一样高留原来的）。
//   --remove <id>：把这块板设成隐藏（rev + 1）。id 永远不删、不重用（R8）：用到它的案例还认得它。
//
// 检查：板材记录要合格（validateBoard），每张图要是 WebP 而且大小和记录一样，文件名只能是 basename（不能有路径）。
// 有任何一块不合格 → 什么都不写，打印原因，退出码 1。合完以后跑一次 npm test（会检查 library.js + public/boards/ 对得上）。
// 随网站发布的板材库出厂是空的（src/shared/boards/library.js）；样板图 / 案例照片永远不要放进这个仓库（它是公开的）。
// 公开的 library.js 只留 3D / 配色 / 案例要用的字段（LIBRARY_KEYS）：没有原来的文件名（员工的文件名里可能有客人的名字）、
// 没有像素大小 / 裁切 / 导入日期 —— 这些只在员工的板材包和那台设备上。v = 这块板 WebP 的指纹（网址带 ?v=，图换了才重新下载）。

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { readPack, cleanRecord, validateBoard, newer, imageKey, webpInfo, IMAGE_TIERS } from '../src/shared/boards/pack.js';
import { boardPath } from '../src/shared/boards/library-api.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const KIND_ORDER = { wood: 0, solid: 1, stone: 2, weave: 3 };

function usage(msg) {
  if (msg) console.error(`✗ ${msg}`);
  console.error('用法：node scripts/import-boards.mjs --pack <板材包.json …> [--meta-only] [--out public/boards] [--library src/shared/boards/library.js] [--dry] [--force] [--remove <id> …]');
  process.exit(2);
}

export function parseArgs(argv) {
  const o = { packs: [], out: path.join(ROOT, 'public/boards'), library: path.join(ROOT, 'src/shared/boards/library.js'), metaOnly: false, dry: false, force: false, remove: [], quiet: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const val = () => {
      const v = argv[++i];
      if (v == null || v.startsWith('--')) usage(`${a} 后面要一个值`);
      return v;
    };
    if (a === '--pack') {
      while (argv[i + 1] && !argv[i + 1].startsWith('--')) o.packs.push(argv[++i]);
    } else if (a === '--out') o.out = path.resolve(val());
    else if (a === '--library') o.library = path.resolve(val());
    else if (a === '--meta-only') o.metaOnly = true;
    else if (a === '--dry' || a === '--dry-run') o.dry = true;
    else if (a === '--force') o.force = true;
    else if (a === '--quiet') o.quiet = true;
    else if (a === '--remove') {
      while (argv[i + 1] && !argv[i + 1].startsWith('--')) o.remove.push(argv[++i]);
    } else if (!a.startsWith('--') && o.packs.length) o.packs.push(a);
    else usage(`不认识的参数 ${a}`);
  }
  if (!o.packs.length && !o.remove.length) usage('要给 --pack（或 --remove）');
  return o;
}

let READS = 0;
/** 读现在的 library.js（不存在 = 空；每次都重新读，不用 Node 缓存的那份） */
export async function readLibrary(file) {
  if (!fs.existsSync(file)) return [];
  const url = `${pathToFileURL(file).href}?t=${Date.now()}-${++READS}`;
  const mod = await import(url);
  return Array.isArray(mod.LIBRARY) ? mod.LIBRARY : [];
}

/** 公开的 library.js 里每条记录留哪些字段（别的 —— file / px / crop / rot / at / lab … —— 只在板材包和员工的设备上） */
export const LIBRARY_KEYS = ['id', 'rev', 'seq', 'code', 'label', 'name', 'series', 'species', 'grain', 'kind', 'finish', 'hex', 'dark', 'light', 'warm', 'mood', 'tags', 'rough', 'proc', 'mm', 'tiers', 'seam', 'uses', 'fav', 'hidden', 'near', 'hash', 'img', 'v'];

/** 一条记录 → 公开的那份（只留 LIBRARY_KEYS） */
export function leanRecord(rec) {
  const out = {};
  for (const k of LIBRARY_KEYS) if (rec[k] !== undefined) out[k] = rec[k];
  return out;
}

/** 贴图的指纹：sha256（1024 + 256 + chip 的 WebP 字节，按这个顺序）的前 8 位 → 网址的 ?v= */
export function imageVersion(byTier) {
  const h = crypto.createHash('sha256');
  for (const t of ['1024', '256', 'chip']) if (byTier[t]) h.update(byTier[t]);
  return h.digest('hex').slice(0, 8);
}

const sortRecords = (list) =>
  [...list].sort((a, b) => (KIND_ORDER[a.kind] ?? 9) - (KIND_ORDER[b.kind] ?? 9) || (a.seq ?? 1e9) - (b.seq ?? 1e9) || String(a.code || a.id).localeCompare(String(b.code || b.id)) || a.id.localeCompare(b.id));

/** library.js 的内容（一条一行，按类别 → 序号 → 编号排；diff 好看） */
export function libraryText(records) {
  const head = [
    '// 溪岸板材库（随网站发布的那一份）—— GENERATED by scripts/import-boards.mjs, do not edit by hand.',
    '// 出厂是空的：真实板材由员工在案例库「板材 · Boards」导入（存在那台设备上），或由负责人用 import-boards.mjs 合进这里。',
    '// 每一条的字段见 src/shared/boards/library-api.js 顶上的说明。',
    'export const LIBRARY_V = 1;',
  ];
  if (!records.length) return [...head, 'export const LIBRARY = [];', ''].join('\n');
  return [...head, 'export const LIBRARY = [', ...sortRecords(records).map((r) => `  ${JSON.stringify(leanRecord(r))},`), '];', ''].join('\n');
}

/**
 * 随网站的板材库对不对得上（npm test 每次都查；合并以后也查）：每条记录合格、id 不重复、没有原来的文件名，
 * img !== false 的板在 <out>/<id>/ 下面有 256 / 1024 / chip 三张 WebP，而且 256 / 1024 的大小和记录的 tiers 一样。
 * @returns {{ ok, errors: string[] }}
 */
export function validateLibrary(records, { out }) {
  const errors = [];
  const seen = new Set();
  for (const r of Array.isArray(records) ? records : []) {
    const id = String(r?.id ?? '?');
    const v = validateBoard(r);
    if (!v.ok) errors.push(`${id}：${v.errors.map((e) => e.zh).join('，')}`);
    if (seen.has(id)) errors.push(`${id}：id 重复`);
    seen.add(id);
    for (const k of Object.keys(r || {})) if (!LIBRARY_KEYS.includes(k)) errors.push(`${id}：公开的板材库不能有「${k}」（只在板材包里）`);
    if (r?.img === false) continue;
    for (const t of IMAGE_TIERS) {
      const f = path.join(out, boardPath(id, t));
      if (!fs.existsSync(f)) {
        errors.push(`${id}：少了 ${path.relative(ROOT, f)}`);
        continue;
      }
      const info = webpInfo(new Uint8Array(fs.readFileSync(f)));
      if (!info) errors.push(`${id}：${t}.webp 不是 WebP`);
      else if (t !== 'chip' && r.tiers?.[t] && (info.w !== r.tiers[t][0] || info.h !== r.tiers[t][1])) errors.push(`${id}：${t}.webp 是 ${info.w} × ${info.h}，记录写的是 ${r.tiers[t].join(' × ')}`);
    }
  }
  return { ok: !errors.length, errors };
}

const hasFiles = (out, id) => fs.existsSync(path.join(out, boardPath(id, 1024))) && fs.existsSync(path.join(out, boardPath(id, 256)));

/**
 * 合并（纯逻辑 + 文件读写分开：plan 先算出要做什么，write 再写）。
 * @returns {{ ok, errors: string[], rejected: [{ file, id, zh }], plan: { records, writes: [{ file, bytes }] }, summary }}
 */
export async function planMerge(o) {
  const errors = [];
  const rejected = [];
  const warnings = [];
  const incoming = new Map();
  const images = new Map();
  for (const f of o.packs) {
    let text;
    try {
      text = fs.readFileSync(f, 'utf8');
    } catch {
      errors.push(`${path.basename(f)}：读不了这个文件`);
      continue;
    }
    const p = readPack(text);
    for (const e of p.errors) errors.push(`${path.basename(f)}：${e.zh}`);
    for (const r of p.rejected) rejected.push({ file: path.basename(f), id: r.id, zh: r.zh });
    for (const w of p.warnings) warnings.push(`${path.basename(f)} ${w.id}：${w.zh}`);
    for (const r of p.boards) {
      const prev = incoming.get(r.id);
      if (prev && !newer(r, prev)) continue;
      incoming.set(r.id, r);
      for (const t of IMAGE_TIERS) {
        const im = p.images.get(imageKey(r.id, t));
        if (im) images.set(imageKey(r.id, t), im.bytes);
      }
    }
  }
  const existing = await readLibrary(o.library);
  const byId = new Map(existing.map((r) => [r.id, r]));
  const sum = { added: [], updated: [], skipped: [], hidden: [], images: 0, bytes: 0 };
  const writes = [];
  for (const [id, rec0] of incoming) {
    const cur = byId.get(id);
    if (!newer(rec0, cur, { force: o.force })) {
      sum.skipped.push(id);
      continue;
    }
    const rec = cleanRecord(rec0);
    const mine = IMAGE_TIERS.map((t) => [t, images.get(imageKey(id, t))]).filter(([, b]) => b);
    if (o.metaOnly) {
      // 只合资料：网站上已经有同一张图（同一个指纹）就继续用，否则近似色
      rec.img = !!(cur?.img !== false && cur?.hash && cur.hash === rec.hash && hasFiles(o.out, id));
    } else if (mine.some(([t]) => t === '1024') && mine.some(([t]) => t === '256')) {
      for (const [t, b] of mine) writes.push({ file: path.join(o.out, boardPath(id, t)), bytes: b });
      sum.images += mine.length;
      sum.bytes += mine.reduce((s, [, b]) => s + b.length, 0);
      rec.img = true;
      rec.v = imageVersion(Object.fromEntries(mine));
    } else {
      rec.img = !!(cur?.hash === rec.hash && hasFiles(o.out, id));
      if (!rec.img) warnings.push(`${id}：包里没有贴图，只合资料`);
    }
    if (rec.img && !rec.v && cur?.v) rec.v = cur.v; // 图没换：网址的 ?v= 跟着原来的
    if (!rec.img) delete rec.v;
    const v = validateBoard(rec);
    if (!v.ok) {
      rejected.push({ file: '', id, zh: v.errors[0].zh });
      continue;
    }
    byId.set(id, rec);
    (cur ? sum.updated : sum.added).push(id);
  }
  for (const id of o.remove) {
    const cur = byId.get(id);
    if (!cur) {
      errors.push(`--remove ${id}：板材库里没有这块板`);
      continue;
    }
    byId.set(id, { ...cur, hidden: true, rev: (cur.rev || 1) + 1 });
    sum.hidden.push(id);
  }
  // 提醒（不挡合并）：同一个序号两块板、木纹没认出树种、比例可能不对、文件名带路径（防万一）
  const all = [...byId.values()];
  const seqs = new Map();
  for (const r of all) if (r.seq != null && !r.hidden) seqs.set(r.seq, [...(seqs.get(r.seq) || []), r.id]);
  for (const [s, ids] of seqs) if (ids.length > 1) warnings.push(`序号 ${s} 有 ${ids.length} 块板：${ids.join(', ')}`);
  for (const r of all) {
    if (r.kind === 'wood' && !r.species && !r.proc) warnings.push(`${r.id}：木纹没有认出树种（近似色木纹按橡木画）`);
    if (r.sizeFlag) warnings.push(`${r.id}：比例可能不对（${r.mm?.join(' × ')} mm）`);
  }
  const ok = !errors.length && !rejected.length;
  return { ok, errors, rejected, warnings, plan: { records: all, writes }, summary: sum };
}

export function writeMerge(o, plan) {
  for (const w of plan.writes) {
    fs.mkdirSync(path.dirname(w.file), { recursive: true });
    fs.writeFileSync(w.file, w.bytes);
  }
  fs.writeFileSync(o.library, libraryText(plan.records));
}

async function main() {
  const o = parseArgs(process.argv.slice(2));
  const r = await planMerge(o);
  const log = (...a) => !o.quiet && console.log(...a);
  for (const e of r.errors) console.error(`✗ ${e}`);
  for (const x of r.rejected) console.error(`✗ ${x.file ? x.file + ' ' : ''}${x.id}：${x.zh}`);
  if (!r.ok) {
    console.error('什么都没写（先修好上面的问题，再合一次）。');
    process.exit(1);
  }
  const s = r.summary;
  log(`板材包 ${o.packs.length} 份 → ${path.relative(ROOT, o.library)}${o.metaOnly ? '（只合资料，--meta-only）' : ''}`);
  log(`  新增 ${s.added.length} · 更新 ${s.updated.length} · 跳过 ${s.skipped.length}（rev 没有更高）${s.hidden.length ? ` · 隐藏 ${s.hidden.length}` : ''}`);
  if (!o.metaOnly) log(`  贴图 ${s.images} 张 · ${(s.bytes / 1024 / 1024).toFixed(1)} MB → ${path.relative(ROOT, o.out)}/<id>/{256,1024,chip}.webp`);
  for (const w of r.warnings) log(`  ! ${w}`);
  if (o.dry) {
    log('（--dry：什么都没写）');
    return;
  }
  writeMerge(o, r.plan);
  log(`✓ 板材库现在 ${r.plan.records.length} 块`);
  log('下一步 · next: run npm test（检查 library.js 和 public/boards/ 对得上，案例 / 3D 的测试照样是绿的），再 npm run build。');
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) main().catch((e) => {
  console.error(e);
  process.exit(1);
});
