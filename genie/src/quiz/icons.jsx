/** <Ico set="who" v="cat" size={26} /> —— 找不到就画一个小圆点，不会报错 */
export function Ico({ set, v, size = 24, stroke = 1.6, className = '' }) {
  const C = ICONS[set]?.[v];
  if (!C) return <span className={`ico-dot ${className}`} style={{ width: size, height: size }} aria-hidden="true" />;
  return <C size={size} strokeWidth={stroke} className={className} aria-hidden="true" />;
}
