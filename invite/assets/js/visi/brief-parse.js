/* ============================================================
   VISI · 读需求卡
   ------------------------------------------------------------
   客户在 brief.html 填完，WhatsApp 上收到的是一段
   「【溪岸 · 客户需求卡】…」文字。整段贴进来，这里把它拆回字段，
   再换算成方案的起手设定：客户名 · 楼盘 · 空间 · 风格 · 需求。
   华文、英文、中英文三种卡都认得（栏位名称表在 assets/js/brief-card.js）。
   ============================================================ */
(function () {
  'use strict';

  var MB = window.MB = window.MB || {};

  /* 栏位名称 → 代号：华文「姓名」、英文「Name」、中英文「姓名 Name」都认（不分大小写） */
  var FALLBACK = {
    name: '姓名', wa: 'WhatsApp', project: '楼盘 / 单位', size: '面积', ptype: '房型', status: '状态',
    keys: '拿钥匙 / 入伙', reno: '硬装进度', scope: '定制范围', style: '风格倾向', ref: '参考图',
    family: '家庭构成', household: '还有谁', cook: '做饭频率', storage: '收纳压力', pain: '最想解决',
    budget: '预算带', decider: '决策人', plan: '平面图', timeline: '期望时间', visitPref: '方便到馆',
    note: '补充', host: '接待'
  };
  var LABELS = {};
  (function () {
    var card = window.SAIL_BRIEF_CARD;
    if (card) {
      Object.keys(card.FIELDS).forEach(function (k) {
        ['zh', 'en', 'bi'].forEach(function (l) { LABELS[card.label(k, l).toLowerCase()] = k; });
      });
    } else {
      // 没载入 brief-card.js：至少认得华文卡
      Object.keys(FALLBACK).forEach(function (k) { LABELS[FALLBACK[k].toLowerCase()] = k; });
    }
  })();

  var LISTS = { scope: 1, style: 1, household: 1, storage: 1, visitPref: 1 };
  /* 巴生谷常见的镇区名 —— 用来分辨「楼盘」和「区域」 */
  var TOWNS = /^(Setia Alam|Shah Alam|Klang|Bukit Jelutong|Kota Kemuning|Bukit Rimau|Puchong|Subang( Jaya)?|USJ|Petaling Jaya|PJ|Damansara.*|Mont Kiara|Bangsar.*|Cheras|Kajang|Cyberjaya|Putrajaya|Seri Kembangan|Rawang|Sungai Buloh|Kuala Lumpur|KL|Ampang|Setapak|Seremban|Semenyih|Bandar.*|Kota Damansara|Ara Damansara|Glenmarie)$/i;

  /* 分段线：〔房产〕、—— 分隔线、【标题】、（由…生成）/ (Generated by …) */
  function structural(line) {
    return /^〔.*〕$/.test(line) || /^[—\-]{3,}/.test(line) || /^【.*】$/.test(line) ||
      /^[（(].*(生成|generated).*[）)]$/i.test(line);
  }

  /** 需求卡文字 → { name, project, scope:[], … }；认不出来返回 null */
  MB.parseBrief = function (text) {
    if (!text || !/[:：]/.test(text)) return null;
    var out = {}, hit = 0, last = null;
    String(text).split(/\r?\n/).forEach(function (raw) {
      var line = raw.trim();
      var m = line.match(/^([^:：]{1,40})[:：]\s*(.*)$/);
      var key = m && LABELS[m[1].trim().toLowerCase()];
      if (!key) {
        // 「最想解决」「补充」是客户自己打的多行字：空行、不认识的「xx：」都接在后面，
        // 只有真正的分段（〔…〕、—— 分隔线、【…】、生成说明）才结束
        if (!line) return;
        if (structural(line)) { last = null; return; }
        if (last === 'pain' || last === 'note') out[last] = (out[last] ? out[last] + '\n' : '') + line;
        return;
      }
      last = key;
      var v = m[2].trim();
      if (!v) return;
      hit++;
      out[key] = LISTS[key] ? v.split(/\s*[、,，]\s*/).filter(Boolean) : v;
    });
    if (out.size) out.size = out.size.replace(/\s*sq\.?\s*ft\.?\s*$/i, '');
    return hit >= 2 ? out : null;
  };

  /** 列表里有没有一项对得上（match 可以是正则或字串） */
  function has(list, match) {
    list = [].concat(list || []);
    for (var i = 0; i < list.length; i++) {
      var s = String(list[i]);
      if (match instanceof RegExp ? match.test(s) : s.indexOf(match) > -1) return true;
    }
    return false;
  }

  /** 「方便到馆」的一项 → 'sat' | 'sun' | 'eve' | 'day'（认不出来 null）。三种语言的卡都认 */
  MB.visitPrefKind = function (s) {
    s = String(s || '');
    if (/周六|星期六|saturday|\bsat\b/i.test(s)) return 'sat';
    if (/周日|星期日|星期天|sunday|\bsun\b/i.test(s)) return 'sun';
    if (/傍晚|晚上|evening|after work/i.test(s)) return 'eve';
    if (/平日|白天|weekday|daytime/i.test(s)) return 'day';
    return null;
  };

  /** 需求卡上客户说「有平面图」吗（华文「平面图：有…」、英文「Floor plan: Yes…」都认） */
  MB.briefSaysPlan = function (text) {
    var m = /^\s*(?:平面图|floor plan)[^:：\n]*[:：]\s*(.*)$/im.exec(String(text || ''));
    return !!m && /^(有|yes)/i.test(m[1].trim());
  };

  /** 拆好的需求卡 → 方案起手设定（不碰销售已经改过的东西，交给 app 合并） */
  MB.briefToSetup = function (b) {
    var setup = { client: {}, property: {}, rooms: [], needs: [], direction: null };
    if (b.name) setup.client.names = b.name;
    if (b.wa) setup.client.wa = MB.msisdn(b.wa);

    if (b.project) {
      // 「楼盘, Setia Alam」/「Setia Alam · 楼盘 B-12-3」→ 楼盘 + 区域（顺序两种都认）
      var parts = b.project.split(/\s*[,，·|/]\s*/).filter(Boolean);
      var townAt = -1;
      parts.forEach(function (s, i) { if (townAt < 0 && TOWNS.test(s)) townAt = i; });
      if (townAt > -1 && parts.length > 1) {
        setup.property.area = parts[townAt];
        setup.property.name = parts.filter(function (s, i) { return i !== townAt; }).join(', ');
      } else {
        setup.property.name = parts[0];
        if (parts.length > 1) setup.property.area = parts.slice(1).join(', ');
      }
    }
    if (b.size) setup.property.size = b.size;
    // 「公寓 Condo」→ Condo；纯华文「公寓」照原样
    if (b.ptype) setup.property.type = b.ptype.replace(/^[^A-Za-z]*\s*/, '') || b.ptype;

    // 空间：定制范围 → 房间（去重，保持 MB.ROOMS 的顺序）
    var want = {};
    (b.scope || []).forEach(function (s) {
      MB.SCOPE_ROOMS.forEach(function (rule) {
        if (has([s], rule.match)) rule.rooms.forEach(function (k) { want[k] = 1; });
      });
    });

    // 需求：做饭 / 收纳 / 同住 → 「你说的 · 我们做的」（公寓用公寓版的落点）
    var probe = { property: setup.property };
    Object.keys(MB.NEEDS).forEach(function (k) {
      var n = MB.NEEDS[k];
      var v = b[n.field];
      if (v && has(v, n.match)) {
        setup.needs.push({ key: k });
        var d = MB.needDef(probe, k);
        want[d.room] = want[d.room] || 2; // 需求点到的空间也带上
      }
    });
    if (b.pain) {
      // 客户自己写的痛点放最前面 —— 原话比我们归纳的选项更有分量
      var own = String(b.pain).split(/[；;。\n]+/).map(function (s) { return s.trim(); }).filter(Boolean)
        .slice(0, 3).map(function (s) {
          var room = MB.guessPainRoom(s);
          if (room) want[room] = want[room] || 2;
          return { quote: s, answer: '', room: room };
        });
      setup.needs = own.concat(setup.needs);
    }

    setup.rooms = MB.ROOMS.map(function (r) { return r.key; }).filter(function (k) { return want[k]; });

    // 风格：取第一个对得上的
    (b.style || []).some(function (s) {
      for (var i = 0; i < MB.STYLE_DIRECTION.length; i++) {
        if (has([s], MB.STYLE_DIRECTION[i].match)) { setup.direction = MB.STYLE_DIRECTION[i].dir; return true; }
      }
      return false;
    });

    setup.visitPref = b.visitPref || [];
    setup.raw = b;
    return setup;
  };
})();
