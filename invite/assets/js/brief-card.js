/* ============================================================
   需求卡（客户在 WhatsApp 发给销售的那段文字）的格式
   ------------------------------------------------------------
   需求卡页（brief.js）照这个「写」，VISI（visi/brief-parse.js）照这个「读」。
   两边共用这一份，改栏位名称只改这里 —— 华文、英文、中英文三种卡都认得。

   一张卡长这样（华文）：
     【溪岸 · 客户需求卡】
     ——————————————
     姓名：Mr & Mrs Lim
     …
     〔房产〕
     楼盘 / 单位：…
     ——————————————
     接待：Wilson Teo
     （由溪岸线上需求卡自动生成）
   英文把每个栏位换成 en；中英文 = 「华文 English」（例：姓名 Name：…）。
   ============================================================ */
(function () {
  'use strict';

  var F = {
    name:      { zh: '姓名',          en: 'Name' },
    wa:        { zh: 'WhatsApp',      en: 'WhatsApp' },
    source:    { zh: '认识渠道',      en: 'Found us via' },
    project:   { zh: '楼盘 / 单位',   en: 'Property & unit' },
    size:      { zh: '面积',          en: 'Size' },
    ptype:     { zh: '房型',          en: 'Property type' },
    status:    { zh: '状态',          en: 'Status' },
    keys:      { zh: '拿钥匙 / 入伙', en: 'Keys / move-in' },
    reno:      { zh: '硬装进度',      en: 'Renovation stage' },
    scope:     { zh: '定制范围',      en: 'Scope' },
    style:     { zh: '风格倾向',      en: 'Style' },
    ref:       { zh: '参考图',        en: 'References' },
    family:    { zh: '家庭构成',      en: 'Family' },
    household: { zh: '还有谁',        en: 'Also at home' },
    cook:      { zh: '做饭频率',      en: 'Cooking' },
    storage:   { zh: '收纳压力',      en: 'Storage pressure' },
    pain:      { zh: '最想解决',      en: 'Most want to solve' },
    budget:    { zh: '预算带',        en: 'Budget range' },
    decider:   { zh: '决策人',        en: 'Decision maker' },
    plan:      { zh: '平面图',        en: 'Floor plan' },
    timeline:  { zh: '期望时间',      en: 'Target date' },
    visitPref: { zh: '方便到馆',      en: 'Showroom visit' },
    note:      { zh: '补充',          en: 'Anything else' },
    host:      { zh: '接待',          en: 'Consultant' }
  };

  var SECTIONS = {
    property: { zh: '房产',       en: 'Property' },
    needs:    { zh: '需求',       en: 'What you need' },
    life:     { zh: '生活习惯',   en: 'How you live' },
    budget:   { zh: '预算与决策', en: 'Budget & decision' },
    next:     { zh: '下一步',     en: 'Next step' }
  };

  var TITLE = { zh: '溪岸 · 客户需求卡', en: 'Sail · Client Brief' };
  var FOOTER = { zh: '由溪岸线上需求卡自动生成', en: 'Generated by the Sail online client brief' };

  function pick(o, lang) {
    if (lang === 'en') return o.en;
    if (lang === 'bi' && o.en !== o.zh) return o.zh + ' ' + o.en;
    return o.zh;
  }

  window.SAIL_BRIEF_CARD = {
    FIELDS: F,
    SECTIONS: SECTIONS,
    /** 栏位名称（不含冒号） */
    label: function (key, lang) { return F[key] ? pick(F[key], lang) : key; },
    /** 冒号：华文、中英文用全角，英文用半角 */
    colon: function (lang) { return lang === 'en' ? ': ' : '：'; },
    /** 列表的分隔：华文、中英文用「、」，英文用逗号（解析两种都认） */
    join: function (lang) { return lang === 'en' ? ', ' : '、'; },
    title: function (lang) {
      return '【' + (lang === 'bi' ? TITLE.zh + ' ' + 'Client Brief' : pick(TITLE, lang)) + '】';
    },
    section: function (key, lang) { return '〔' + pick(SECTIONS[key], lang) + '〕'; },
    footer: function (lang) {
      if (lang === 'en') return '(' + FOOTER.en + ')';
      if (lang === 'bi') return '（' + FOOTER.zh + ' · ' + FOOTER.en + '）';
      return '（' + FOOTER.zh + '）';
    },
    rule: '——————————————'
  };
})();
